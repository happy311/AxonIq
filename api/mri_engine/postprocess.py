from __future__ import annotations
import datetime

import numpy as np
from scipy import ndimage

from api.mri_engine.config import MIN_COMPONENT_VOXELS, ZONE_NAMES, CELL_NAME
from api.mri_engine.model import MODEL_ARCH_NAME


def suppress_small_components(prob_vol, mask_bin, min_size=MIN_COMPONENT_VOXELS):
    labeled, n_components = ndimage.label(mask_bin)
    if n_components == 0:
        return prob_vol.copy(), mask_bin.copy()
    sizes = ndimage.sum(mask_bin, labeled, range(1, n_components + 1))
    small_labels = [i + 1 for i, s in enumerate(sizes) if s < min_size]
    prob_out = prob_vol.copy()
    mask_out = mask_bin.copy()
    if small_labels:
        remove = np.isin(labeled, small_labels)
        prob_out[remove] = 0.0
        mask_out[remove] = 0
    return prob_out, mask_out


def build_zone_report(pred_mask: np.ndarray, zone_vol: np.ndarray, spacing) -> list:
    voxel_vol_mm3 = float(np.prod(spacing))
    pred_bool = pred_mask.astype(bool)
    regions = []
    for zone_id, zone_name in ZONE_NAMES.items():
        overlap = pred_bool & (zone_vol == zone_id)
        n_vox = int(overlap.sum())
        if n_vox == 0:
            continue
        _, n_lesions = ndimage.label(overlap)
        regions.append({
            "region": zone_name,
            "num_lesions": int(n_lesions),
            "num_voxels": n_vox,
            "lesion_volume_mm3": round(n_vox * voxel_vol_mm3, 4),
        })
    unclassified = pred_bool & (zone_vol == 0)
    n_unclassified = int(unclassified.sum())
    if n_unclassified > 0:
        _, n_lesions = ndimage.label(unclassified)
        regions.append({
            "region": "Unclassified (outside WM mask)",
            "num_lesions": int(n_lesions),
            "num_voxels": n_unclassified,
            "lesion_volume_mm3": round(n_unclassified * voxel_vol_mm3, 4),
        })
    return sorted(regions, key=lambda r: -r["lesion_volume_mm3"])


def build_report(case_id: str, pred_mask: np.ndarray, regions: list, spacing,
                  preprocessing_info: dict, norm_method_used: str, n_models: int) -> dict:
    voxel_vol_mm3 = float(np.prod(spacing))
    _, total_lesions = ndimage.label(pred_mask)
    total_voxels = int(pred_mask.sum())
    total_volume = round(total_voxels * voxel_vol_mm3, 4)

    lines = [
        "",
        "AI ENSEMBLE MS LESION SEGMENTATION REPORT",
        "==========================================",
        "",
        f"Case                          : {case_id}",
        f"Model                         : {MODEL_ARCH_NAME} | {n_models}-model "
        f"orientation ensemble (axial/coronal/sagittal, cell: {CELL_NAME})",
        f"Registration                  : {preprocessing_info['registration_mode'].upper()}"
        f" (auto-detected: already_on_MNI_grid={preprocessing_info['already_on_mni_grid']})",
        f"Skull-strip                   : {preprocessing_info['skull_strip_mode'].upper()}"
        f" (auto-detected: likely_already_stripped={preprocessing_info['likely_already_skull_stripped']})",
        f"Intensity normalization       : {norm_method_used} (always on, per config)",
        "",
        "OVERALL LESION BURDEN",
        "----------------------",
        f"Total Number of Lesions       : {total_lesions} lesions",
        f"Total Lesion Voxels           : {total_voxels} voxels",
        f"Total Lesion Volume           : {total_volume:.2f} mm\u00b3",
        "",
        "LESION DISTRIBUTION BY ANATOMICAL ZONE",
        "---------------------------------------",
    ]
    for r in regions:
        lines += [
            "",
            f"Zone                       : {r['region']}",
            f"Number of Lesions          : {r['num_lesions']} lesions",
            f"Lesion Voxels              : {r['num_voxels']} voxels",
            f"Lesion Volume              : {r['lesion_volume_mm3']:.2f} mm\u00b3",
            "----------------------------------------------------",
        ]
    lines += [
        "",
        "NOTES",
        "-----",
        "\u2022 Lesion count is the number of connected lesion components (6-connectivity).",
        "\u2022 Lesion volume is reported in cubic millimetres (mm\u00b3).",
        "\u2022 Zones (Periventricular/Juxtacortical/Infratentorial/Deep WM) are a heuristic "
        "distance-from-tissue-map classification, not a validated clinical atlas.",
        f"\u2022 Segmentation generated by a {n_models}-model orientation ensemble "
        "(smp.Unet resnet34+SCSE, one model per axial/coronal/sagittal view), CPU inference.",
        "",
    ]

    return {
        "case_id": case_id,
        "generated_at": datetime.datetime.utcnow().isoformat() + "Z",
        "model": {
            "architecture": MODEL_ARCH_NAME,
            "cell_name": CELL_NAME,
            "n_models_in_ensemble": n_models,
            "modalities": ["FLAIR"],
        },
        "preprocessing": {**preprocessing_info, "intensity_normalize_method": norm_method_used},
        "overall": {
            "total_lesions": int(total_lesions),
            "total_voxels": total_voxels,
            "total_volume_mm3": total_volume,
        },
        "regions": regions,
        "report_text": "\n".join(lines),
    }
